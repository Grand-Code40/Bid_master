// Pure domain component only. Caller must authenticate ctx server-side, validate
// listing availability, and persist transitions with atomic compare-and-swap.
// Never derive ctx.role, ctx.now or ctx.newClaimToken from browser JSON.
const fail = code => { throw new Error(code); };
function checkedText(value, limit=8000) {
  if (typeof value !== 'string' || !value.trim() || [...value].length>limit || value.includes('\0')) fail('invalid_text');
  return value.trim();
}
function deliveryLink(value, recipient) {
  if (value == null) return null;
  if (typeof value !== 'string' || value.length>2048 || /[\x00-\x20]/.test(value)) fail('invalid_delivery_url');
  let url, target;
  try { url=new URL(value); target=new URL(recipient); } catch { fail('invalid_delivery_url'); }
  if (url.protocol!=='https:' || url.port || url.username || url.password || url.hostname!==target.hostname) fail('invalid_delivery_url');
  url.search=''; url.hash=''; return url.href;
}
// Fixed-length token comparison avoids a character-position early exit.
// Tokens must be generated by the server using a cryptographic random source.
function tokenMatches(a,b) {
  if(typeof a!=='string'||typeof b!=='string'||a.length!==32||b.length!==32) return false;
  let mismatch=0; for(let i=0;i<32;i++) mismatch |= a.charCodeAt(i)^b.charCodeAt(i);
  return mismatch===0;
}
export function transition(current, command, ctx) {
  if (!ctx || !['owner','agent'].includes(ctx.role)) fail('unauthorized');
  const {action}=command;
  if (!['save','approve','queue','cancel','claim','result','record_manual_delivery'].includes(action)) fail('invalid_action');
  if (['approve','queue','cancel','record_manual_delivery'].includes(action) && ctx.role!=='owner') fail('owner_required');
  if (['claim','result'].includes(action) && ctx.role!=='agent') fail('agent_required');
  if (typeof ctx.now!=='string' || !Number.isFinite(Date.parse(ctx.now))) fail('invalid_clock');
  if(current.state==='manual_sent'||current.manual_delivery) fail('review_locked');
  const row={...current};
  if (!['claim','result'].includes(action) && (!Number.isSafeInteger(command.revision) || command.revision!==row.revision)) fail('stale_revision');
  if(action==='record_manual_delivery') {
    return recordManualDelivery(row,command,ctx);
  } else if(action==='save') {
    const text=checkedText(command.text);
    if (!['draft','approved'].includes(row.state)) fail('review_locked');
    if (text===row.text) return row;
    Object.assign(row,{text,revision:row.revision+1,state:'draft',approved_revision:null});
  } else if(action==='approve') {
    if (!['draft','approved'].includes(row.state)) fail('review_locked');
    Object.assign(row,{state:'approved',approved_revision:row.revision});
  } else if(action==='queue') {
    if(row.state==='queued' && row.approved_revision===row.revision) return row;
    if(row.state!=='approved'||row.approved_revision!==row.revision) fail('approval_required');
    row.state='queued';
  } else if(action==='cancel') {
    if(!['queued','approved'].includes(row.state)) fail('review_locked');
    Object.assign(row,{state:'draft',revision:row.revision+1,approved_revision:null});
  } else if(action==='claim') {
    if(row.state!=='queued') fail('review_locked');
    if(row.approved_revision!==row.revision) fail('approval_required');
    if(typeof ctx.newClaimToken!=='string'|| !/^[A-Za-z0-9_-]{32}$/.test(ctx.newClaimToken)) fail('invalid_claim_token');
    Object.assign(row,{state:'sending',claim_token:ctx.newClaimToken,claimed_at:ctx.now});
  } else {
    if(!['sent','not_sent','uncertain'].includes(command.outcome)) fail('invalid_outcome');
    const evidence=checkedText(command.evidence,2000);
    if(!tokenMatches(command.claim_token,row.claim_token)) fail('claim_mismatch');
    const delivery_url=deliveryLink(command.delivery_url,row.canonical_url);
    if(row.state==='sent'&&command.outcome==='sent') return row;
    if(!['sending','uncertain'].includes(row.state)) fail('review_locked');
    Object.assign(row,{state:command.outcome==='not_sent'?'draft':command.outcome,evidence,delivery_url});
    if(command.outcome==='not_sent') Object.assign(row,{revision:row.revision+1,approved_revision:null,claim_token:null,claimed_at:null});
  }
  // A text revision, cancellation or proven non-delivery requires new
  // explicit per-delivery consent, not reuse of a previous sending snapshot.
  if(row.revision!==current.revision) { delete row.delivery_confirmation; delete row.delivery_attempt_id; }
  row.updated_at=ctx.now;
  return row;
}
export function publicReview(row) {
  const keys=['source_id','external_id','canonical_url','title','text','revision','state','approved_revision','created_at','updated_at','claimed_at','evidence','delivery_url','delivery_confirmation','manual_delivery','delivery_attempt_id'];
  return Object.fromEntries(keys.filter(key=>Object.hasOwn(row,key)).map(key=>[key,row[key]]));
}

// Owner-attested historical fact, not automatic sender success or a read receipt.
// Exact allowlist deliberately rejects URL normalization, extra/duplicate params,
// fragments, credentials, alternate hosts, encoded digits and query secrets.
export function manualDeliveryUrl(value) {
  if(typeof value!=='string'||!/^https:\/\/vmasshtabe\.ru\/account\/view-task\?id=[1-9][0-9]{0,19}&response_id=[1-9][0-9]{0,19}$/.test(value)) fail('invalid_manual_delivery');
  return value;
}
function recordManualDelivery(row,command,ctx) {
  if(!['draft','approved','queued'].includes(row.state)||row.manual_delivery) fail('review_locked');
  const d=command.details;
  const keys=['text','observation','observed_at','delivery_url'];
  if(row.source_id!=='vmasshtabe'||!d||typeof d!=='object'||Array.isArray(d)||Object.keys(d).length!==keys.length||keys.some(k=>!Object.hasOwn(d,k))) fail('invalid_manual_delivery');
  if(d.text!==row.text) fail('confirmation_mismatch');
  checkedText(d.text);
  checkedText(d.observation,2000);
  // Require a real UTC instant; reject rollover dates and future observations.
  const at=typeof d.observed_at==='string'?Date.parse(d.observed_at):NaN;
  if(!Number.isFinite(at)||new Date(at).toISOString()!==d.observed_at||at>Date.parse(ctx.now)) fail('invalid_manual_delivery');
  const snapshot={version:1,source_id:row.source_id,external_id:row.external_id,canonical_url:row.canonical_url,revision:row.revision,text:row.text,observation:d.observation,observed_at:d.observed_at,recorded_at:ctx.now,delivery_url:manualDeliveryUrl(d.delivery_url)};
  return {...row,state:'manual_sent',manual_delivery:snapshot,updated_at:ctx.now};
}
